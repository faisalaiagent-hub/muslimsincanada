import assert from 'node:assert/strict';
import fs from 'node:fs';
import { decodePoint, distanceKm, validPoint, rankNearby } from '../lib/nearby.ts';
const point = decodePoint('0101000020E6100000280F0BB5A6DD53C05D6DC5FEB2D34540');
assert.ok(point && point.latitude > 43 && point.latitude < 44 && point.longitude > -80 && point.longitude < -79);
assert.equal(decodePoint('not coordinates'), null);
assert.equal(decodePoint(null), null);
assert.equal(validPoint({ latitude: 91, longitude: 10 }), false);
assert.equal(distanceKm({ latitude: 0, longitude: 0 }, { latitude: 0, longitude: 0 }), 0);
const toronto = { latitude: 43.6532, longitude: -79.3832 }, ottawa = { latitude: 45.4215, longitude: -75.6972 };
assert.ok(distanceKm(toronto, ottawa) > 340 && distanceKm(toronto, ottawa) < 360);
assert.ok(Math.abs(distanceKm(toronto, ottawa) - distanceKm(ottawa, toronto)) < .001);
const rows = JSON.parse(fs.readFileSync('data/nearby/food-places.json', 'utf8'));
assert.equal(new Set(rows.map(row => row.id)).size, rows.length);
assert.ok(rows.every(row => row.sourceUrl.startsWith('https://') && (row.sourceUrl.startsWith('https://hmacanada.org/') || row.halalBasis === 'owner-declared')));
const mosques = JSON.parse(fs.readFileSync('data/nearby/mosque-locations.json', 'utf8'));
// Public Ringwood Drive landmark, not a user's device location.
const stouffville = { latitude: 43.963028, longitude: -79.273372 };
const nearby = rankNearby([...rows, ...mosques], stouffville, 25);
assert.ok(nearby.some(row => /Dar.ul.Khair/i.test(row.name)));
assert.ok(nearby.some(row => /Darul Iman/i.test(row.name)));
assert.ok(nearby.filter(row => row.type === 'food' && /Stouffville/i.test(row.city)).length >= 3);
assert.ok(nearby.every((row, index) => !index || row.distance >= nearby[index - 1].distance));
assert.ok(rankNearby([...rows, ...mosques], stouffville, 50).length >= nearby.length);
assert.equal(rankNearby([{ ...rows[0], latitude: null }], stouffville, 25).length, 0);
assert.ok(rows.filter(row => row.latitude !== null).every(row => validPoint(row) && row.coordinateLicence === 'ODbL-1.0'));
const base = process.env.MIC_TEST_URL || 'http://localhost:3103';
let response = await fetch(base + '/api/areas', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ query: 'Mississauga' }) });
assert.equal(response.status, 200);
const result = await response.json();
assert.ok(result.areas.some(area => /Mississauga/.test(area.name) && validPoint(area)));
await new Promise(resolve => setTimeout(resolve, 2100));
response = await fetch(base + '/api/areas', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ query: 'L4A 0P4' }) });
assert.equal(response.status, 200);
const postalResult = await response.json();
assert.ok(postalResult.areas.length > 0);
assert.ok(postalResult.areas.every(area => /L4A/.test(area.name) && /Stouffville/.test(area.name)));
const liveDirectory = await (await fetch(base + '/api/nearby')).json();
const postalNearby = rankNearby(liveDirectory.places, postalResult.areas[0], 25);
assert.ok(postalNearby.some(row => /Dar.ul.Khair/i.test(row.name)));
assert.ok(postalNearby.some(row => /Darul Iman/i.test(row.name)));
assert.ok(postalNearby.filter(row => row.type === 'food').length > 4);
response = await fetch(base + '/api/areas', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'https://unrelated.example' }, body: JSON.stringify({ query: 'Toronto' }) });
assert.equal(response.status, 403);
response = await fetch(base + '/api/areas', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ query: 'x' }) });
assert.equal(response.status, 400);
for (const path of ['/nearby', '/nearby?type=food', '/nearby?type=mosque']) {
  response = await fetch(base + path); assert.equal(response.status, 200);
  assert.ok((await response.text()).includes('Use my location'));
}
response = await fetch(base + '/data/nearby-food.json'); assert.equal(response.status, 200);
assert.equal((await response.json()).licence, 'ODbL-1.0');
console.log(`PASS: geographic decoding/distance checks, ${rows.length} attributed food records, Canadian area lookup, API validation, three discovery URLs and licence export.`);
